/* Rebuild generated English assets and compact CSS from the Arabic source.
   Fails on untranslated Arabic UI strings. No production runtime dependencies. */
const fs=require('node:fs'),path=require('node:path'),acorn=require('acorn'),{JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'..'), dict=JSON.parse(fs.readFileSync(path.join(__dirname,'en.json'),'utf8'));
const arabic=/[\u0621-\u064a]/,missing=new Set();
function translate(s){
 if(Object.hasOwn(dict,s))return dict[s];
 const trimmed=s.trim();if(Object.hasOwn(dict,trimmed))return s.slice(0,s.indexOf(trimmed))+dict[trimmed]+s.slice(s.indexOf(trimmed)+trimmed.length);
 if(arabic.test(s))missing.add(s);return s;
}
fs.mkdirSync(path.join(root,'en'),{recursive:true});
const files=['data.js','quote.js','picker.js','draft.js','app.js','validation.js','navigation.js','demonstrations.js','inquiry.js'];
for(const f of files){
 let source=fs.readFileSync(path.join(root,f),'utf8'),edits=[];const tree=acorn.parse(source,{ecmaVersion:'latest'});
 function walk(n){if(!n||typeof n!=='object')return;
  if(n.type==='Literal'&&typeof n.value==='string'&&arabic.test(n.value)&&n.value!=='و '){edits.push([n.start,n.end,JSON.stringify(translate(n.value))]);}
  for(const v of Object.values(n))if(Array.isArray(v))v.forEach(walk);else if(v&&typeof v==='object')walk(v);
 }walk(tree);for(const [a,b,v] of edits.sort((a,b)=>b[0]-a[0]))source=source.slice(0,a)+v+source.slice(b);
 if(f==='quote.js')source=source.replaceAll("'ar-EG'","'en-EG'").replace('const name = RLI + bidiText(label) + PDI;','const name = LRI + bidiText(label) + PDI;').replace("' — ' + RLI", "' — ' + LRI");
 if(f==='demonstrations.js')source=source.replaceAll('"demos/','"../demos/');
 fs.writeFileSync(path.join(root,'en',f),'/* Generated by tools/build.cjs. Edit the root source, then rebuild. */\n'+source);
}
const dom=new JSDOM(fs.readFileSync(path.join(root,'index.html'),'utf8')),doc=dom.window.document;
function walkText(n){for(const c of [...n.childNodes]){if(c.nodeType===3){if(arabic.test(c.data))c.data=translate(c.data);else if(c.data.trim()==='←')c.data=c.data.replace('←','→');else if(c.data.trim()==='→')c.data=c.data.replace('→','←');}else if(c.nodeType===1&& !['SCRIPT','STYLE'].includes(c.tagName))walkText(c);}}
walkText(doc.documentElement);
for(const e of doc.querySelectorAll('*'))for(const a of ['title','aria-label','placeholder','content','alt'])if(e.hasAttribute(a)&&arabic.test(e.getAttribute(a)))e.setAttribute(a,translate(e.getAttribute(a)));
for(const e of doc.querySelectorAll('script[type="application/ld+json"]')){
 function tr(v){if(typeof v==='string')return arabic.test(v)?translate(v):v;if(Array.isArray(v))return v.map(tr);if(v&&typeof v==='object')return Object.fromEntries(Object.entries(v).map(([k,x])=>[k,tr(x)]));return v;}
 const data=tr(JSON.parse(e.textContent));if(data['@type']==='LocalBusiness')data.url='https://warshabeteya.github.io/warshabeteya/en/';e.textContent=JSON.stringify(data);
}
doc.documentElement.lang='en';doc.documentElement.dir='ltr';
doc.querySelector('[rel=canonical]').href='https://warshabeteya.github.io/warshabeteya/en/';
doc.querySelector('[property="og:url"]').content='https://warshabeteya.github.io/warshabeteya/en/';doc.querySelector('[property="og:locale"]').content='en_EG';
const lang=doc.querySelector('.language-switch');lang.href='../';lang.textContent='العربية';lang.lang='ar';lang.dir='rtl';lang.hreflang='ar-EG';
for(const e of doc.querySelectorAll('link[href],img[src],script[src]')){
 const attr=e.hasAttribute('src')?'src':'href',v=e.getAttribute(attr);
 if(/^(https?:|#|\/)/.test(v))continue;
 if(e.tagName==='SCRIPT'&&files.includes(v.split('?')[0]))continue;
 e.setAttribute(attr,'../'+v);
}
const directionStyle=doc.createElement('style');directionStyle.textContent='.choice-name{text-align:start}@media(max-width:760px){.device-card svg{float:left;margin:0 12px 0 0}}';doc.head.append(directionStyle);
fs.writeFileSync(path.join(root,'en/index.html'),'<!doctype html>\n'+doc.documentElement.outerHTML);
const css=['style.css','inquiry.css','journey.css','clarity.css'].map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n');
fs.writeFileSync(path.join(root,'site.css'),css.replace(/\/\*[\s\S]*?\*\//g,'').replace(/\s+/g,' ').replace(/\s*([{};])\s*/g,'$1').trim());
if(missing.size){console.error('Missing English translations:',[...missing]);process.exit(1);}console.log('Built English pages/scripts and site.css; all UI strings translated.');
